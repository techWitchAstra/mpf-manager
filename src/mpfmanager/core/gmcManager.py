from __future__ import annotations

# The following imports zip, file and process utilities used to fetch and write GMC projects
import io
import re
import shutil
import subprocess
import zipfile
from pathlib import Path

from packaging.version import InvalidVersion, Version

from mpfmanager.core import compatibilityManager
from mpfmanager.core.storageManager import VirtualEnvironment

# The following defines where GMC releases are found on github
GMC_TAGS_URL = "https://api.github.com/repos/missionpinball/mpf-gmc/tags?per_page=100"
GMC_ARCHIVE_URL = "https://github.com/missionpinball/mpf-gmc/archive/refs/tags/v{version}.zip"
GMC_ADDON_RELATIVE = Path("addons") / "mpf-gmc"

# The following is the oldest godot that supports importing a project from the command line
GODOT_IMPORT_MIN_VERSION = Version("4.3")
GODOT_DEFAULT_FEATURE = "4.4"
_GODOT_VERSION_RE = re.compile(r"^(\d+)\.(\d+)")
_EXECUTABLE_LINE_RE = re.compile(r"^;?executable_path=.*$", re.MULTILINE)
_MPF_SECTION_RE = re.compile(r"^\[mpf\][ \t]*$", re.MULTILINE)

PROJECT_GODOT_TEMPLATE = """\
; Engine configuration file.
; Generated by MPF-Manager, it's best edited using the Godot editor from here on.

config_version=5

[application]

config/name="{projectName}"
run/main_scene="res://addons/mpf-gmc/slides/window.tscn"
config/features=PackedStringArray("{godotFeature}")

[autoload]

MPF="*res://addons/mpf-gmc/mpf_gmc.gd"

[display]

window/size/viewport_width={width}
window/size/viewport_height={height}

[editor_plugins]

enabled=PackedStringArray("res://addons/mpf-gmc/plugin.cfg")

[filesystem]

import/blender/enabled=false
"""

GMC_CFG_TEMPLATE = """\
; GMC configuration, generated by MPF-Manager
; See https://missionpinball.org for the full reference

[gmc]

fullscreen=false
exit_on_esc=true
logging_global=20

[keyboard]

enter=["switch", "s_start"]

[mpf]

; spawn_mpf lets GMC launch MPF itself using the executable below
spawn_mpf=false
virtual=true
verbose=false
{executableLine}
"""

GITIGNORE_TEMPLATE = """\
# Godot 4 generated files
.godot/
*.translation
"""


# The following escapes a value so it can be written inside quotes in a godot config file
def _godotString(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


# The following builds the gmc.cfg line pointing GMC at an mpf executable
def _executableLine(mpfExecutable: Path | None) -> str:
    if mpfExecutable is None:
        return ";executable_path="
    return f'executable_path="{_godotString(mpfExecutable.as_posix())}"'


# The following lists the mpf-gmc versions published as git tags, newest first
def listGMCVersions() -> list[str]:
    """returns available mpf-gmc versions from github tags"""
    gmcVersions = []
    for tag in compatibilityManager.jsonRetriever(GMC_TAGS_URL) or []:
        tagName = str(tag.get("name", "")).removeprefix("v")
        try:
            Version(tagName)
        except InvalidVersion:
            continue
        gmcVersions.append(tagName)
    return sorted(gmcVersions, key=Version, reverse=True)


# The following asks an environment's MPF which GMC version it was built against
def requiredGMCVersion(virtualEnvironment: VirtualEnvironment) -> str | None:
    """returns mpf._version.__gmc_version__ from inside the environment, or None if it isn't available"""
    try:
        output = subprocess.run(
            [
                str(virtualEnvironment.executable("python")),
                "-c",
                "import mpf._version as v; print(getattr(v, '__gmc_version__', ''))",
            ],
            capture_output=True,
            text=True,
            check=True,
            timeout=60,
        ).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return None
    return output or None


# The following extracts the addon folder from a GMC release archive into a staging folder
def _extractGMCAddon(archiveBytes: bytes, stagingFolder: Path) -> None:
    resolvedStaging = stagingFolder.resolve()
    with zipfile.ZipFile(io.BytesIO(archiveBytes)) as archive:
        for member in archive.infolist():
            memberParts = Path(member.filename).parts
            if member.is_dir() or len(memberParts) < 4 or memberParts[1:3] != GMC_ADDON_RELATIVE.parts:
                continue

            # The following refuses any member that would be written outside of the staging folder
            destination = (stagingFolder / Path(*memberParts[1:])).resolve()
            if not destination.is_relative_to(resolvedStaging):
                raise ValueError(f"Refusing unsafe path in GMC archive: {member.filename}")
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(archive.read(member))


# The following downloads (or re-uses a cached copy of) the mpf-gmc addon for a version
def fetchGMCAddon(gmcVersion: str, cacheDirectory: Path) -> Path:
    """returns the path to a cached addons/mpf-gmc folder for the requested version"""

    cachedAddon = cacheDirectory / gmcVersion / GMC_ADDON_RELATIVE
    if (cachedAddon / "plugin.cfg").is_file():
        return cachedAddon

    # The following downloads into a staging folder so a half download is never treated as cached
    archiveBytes = compatibilityManager.urlRetriever(GMC_ARCHIVE_URL.format(version=gmcVersion), 120)
    stagingFolder = cacheDirectory / f".{gmcVersion}.partial"
    shutil.rmtree(stagingFolder, ignore_errors=True)
    stagingFolder.mkdir(parents=True)
    try:
        _extractGMCAddon(archiveBytes, stagingFolder)
        if not (stagingFolder / GMC_ADDON_RELATIVE / "plugin.cfg").is_file():
            raise FileNotFoundError(f"mpf-gmc v{gmcVersion} archive did not contain addons/mpf-gmc/plugin.cfg")
    except Exception:
        shutil.rmtree(stagingFolder, ignore_errors=True)
        raise

    # The following moves the finished download into place
    shutil.rmtree(cacheDirectory / gmcVersion, ignore_errors=True)
    stagingFolder.rename(cacheDirectory / gmcVersion)
    return cachedAddon


# The following reads the major.minor version of an installed godot executable
def godotVersion(godotExecutable: str) -> Version | None:
    """returns the godot version (e.g. 4.4) or None if it can't be determined"""
    try:
        output = subprocess.run(
            [godotExecutable, "--version"], capture_output=True, text=True, check=True, timeout=60
        ).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return None
    match = _GODOT_VERSION_RE.match(output)
    return Version(f"{match.group(1)}.{match.group(2)}") if match else None


# The following creates a blank godot project with GMC configured
def createGMCProject(
    gmcProjectPath: Path,
    projectName: str,
    addonSource: Path,
    godotFeature: str = GODOT_DEFAULT_FEATURE,
    mpfExecutable: Path | None = None,
    viewportSize: tuple[int, int] = (1280, 720),
) -> Path:
    """writes project.godot, gmc.cfg and the mpf-gmc addon into a folder (usually the MPF machine folder)"""

    # First a check is run so an existing godot project is never overwritten
    if (gmcProjectPath / "project.godot").exists():
        raise FileExistsError(f"'{gmcProjectPath}' already contains a project.godot")
    if (gmcProjectPath / GMC_ADDON_RELATIVE).exists():
        raise FileExistsError(f"'{gmcProjectPath / GMC_ADDON_RELATIVE}' already exists")

    # The following copies in the addon and creates the folders GMC looks for slides and widgets in
    gmcProjectPath.mkdir(parents=True, exist_ok=True)
    shutil.copytree(addonSource, gmcProjectPath / GMC_ADDON_RELATIVE)
    for folder in ("slides", "widgets"):
        (gmcProjectPath / folder).mkdir(exist_ok=True)

    # The following writes the godot project file
    (gmcProjectPath / "project.godot").write_text(
        PROJECT_GODOT_TEMPLATE.format(
            projectName=_godotString(projectName),
            godotFeature=godotFeature,
            width=viewportSize[0],
            height=viewportSize[1],
        ),
        encoding="utf-8",
    )

    # The following writes gmc.cfg, pointing it at the environment's mpf when one is known
    (gmcProjectPath / "gmc.cfg").write_text(
        GMC_CFG_TEMPLATE.format(executableLine=_executableLine(mpfExecutable)), encoding="utf-8"
    )

    # The following keeps godot's generated files out of version control
    gitignore = gmcProjectPath / ".gitignore"
    if not gitignore.exists():
        gitignore.write_text(GITIGNORE_TEMPLATE, encoding="utf-8")
    elif ".godot/" not in gitignore.read_text(encoding="utf-8"):
        with gitignore.open("a", encoding="utf-8") as gitignoreFile:
            gitignoreFile.write("\n" + GITIGNORE_TEMPLATE)
    return gmcProjectPath


# The following points an existing gmc.cfg at a different mpf executable
def updateGMCExecutable(gmcProjectPath: Path, mpfExecutable: Path | None) -> bool:
    """rewrites the [mpf] executable_path in gmc.cfg, returns false if there is no gmc.cfg"""
    gmcConfig = gmcProjectPath / "gmc.cfg"
    if not gmcConfig.is_file():
        return False
    configText = gmcConfig.read_text(encoding="utf-8")
    newLine = _executableLine(mpfExecutable)

    # The following replaces the existing line, or adds one to the [mpf] section if there isn't one
    if _EXECUTABLE_LINE_RE.search(configText):
        configText = _EXECUTABLE_LINE_RE.sub(lambda _match: newLine, configText, count=1)
    elif _MPF_SECTION_RE.search(configText):
        configText = _MPF_SECTION_RE.sub(lambda match: f"{match.group(0)}\n{newLine}", configText, count=1)
    else:
        configText = configText.rstrip("\n") + f"\n\n[mpf]\n\n{newLine}\n"
    gmcConfig.write_text(configText, encoding="utf-8")
    return True


# The following builds the command that imports the project's assets headlessly so the editor opens cleanly
def importGMCProject(godotExecutable: str, gmcProjectPath: Path) -> list[str]:
    """returns the godot command that builds the .godot import cache (godot 4.3+)"""
    return [godotExecutable, "--headless", "--path", str(gmcProjectPath), "--import"]
